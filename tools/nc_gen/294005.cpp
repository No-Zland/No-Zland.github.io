// NC294005 露西的蛋糕
// 题意：长度 2^n 的纸条，做 m 次「后半截翻折到前半截之上」，折叠后长度 L = 2^(n-m)。
//       在折叠后最上层、距左端 x 处染色，问该处原本距原纸条左端的长度。
// 结论：answer = 2 * L + 1 - x = 2^(n-m+1) + 1 - x。
// 推导：
//   1) 每摞纸的最底层永远是原位置 p 本身——前半截从不被搬动，只往上压新层；
//   2) 最后一次折叠把后半截第 q 格整摞翻过来盖到第 2L+1-q 格上，翻转会把这一摞
//      上下颠倒，于是「翻转前的最底层」变成「翻转后的最顶层」；
//   3) 最顶层 = 翻转前位置 2L+1-x 的最底层 = 原纸条位置 2L+1-x。
//   只有最后一次折叠决定最上层，所以答案只与 n-m 和 x 有关。
#include <cstdio>
int main() {
    long long n, m, x;
    if (scanf("%lld %lld %lld", &n, &m, &x) != 3) return 0;
    long long L = 1LL << (n - m);        // 折叠后长度，保证 0 <= n-m <= 40
    printf("%lld\n", 2LL * L + 1 - x);   // 最顶层来自原纸条的镜像位置
    return 0;
}
