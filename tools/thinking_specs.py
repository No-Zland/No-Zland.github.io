def safe(t):
    return t.replace("[", "【").replace("]", "】")


def fmt_nc(pid):
    x = NCMAP.get(pid)
    if not x:
        raise KeyError(pid)
    box = "x" if x["ac"] else " "
    extra = "" if x["ac"] else f" · 试过 {x['attempts']} 次"
    return f"- [{box}] [{safe(x['title'])}](https://ac.nowcoder.com/acm/problem/{pid}) · 牛客{extra}"


def fmt_lg(pid):
    t = LG.get(pid, "")
    t = t.replace(f"{pid} ", "")
    return f"- [ ] [{safe(t)}](https://www.luogu.com.cn/problem/{pid}) · 洛谷"


def main():
    os.makedirs(OUT, exist_ok=True)
    meta = []
    for a in ARTICLES:
        lines = [fmt_nc(p) for p in a["nc"]] + [fmt_lg(p) for p in a["lg"]]
        done = sum(1 for l in lines if l.startswith("- [x]"))
        spec = dict(a)
        spec["list_md"] = "\n".join(lines)
        spec["total"] = len(lines)
        spec["done"] = done
        json.dump(spec, open(os.path.join(OUT, a["key"] + ".json"), "w", encoding="utf-8"),
                  ensure_ascii=False, indent=1)
        meta.append(dict(key=a["key"], file=a["file"], title=a["title"],
                         total=len(lines), done=done))
    json.dump(meta, open(os.path.join(OUT, "meta.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    print(f"{len(ARTICLES)} articles")
    for m in meta:
        print(f"{m['done']:2d}/{m['total']:2d}  {m['title']}")


if __name__ == "__main__":
    main()
